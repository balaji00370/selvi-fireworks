"""Builds supabase/migrations/002_seed_products.sql from the price list in booknow.html.
Run again whenever prices or products change on the Book Now page:
    python supabase/tools/gen_products_sql.py
then run the new 002 file in the Supabase SQL editor (it updates existing rows)."""
import html
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
src = open(os.path.join(ROOT, 'booknow.html'), encoding='utf-8').read()

rows = []
cat = ''
pos = 0
for m in re.finditer(r'<span>([^<]*)</span>\s*<span class="cat-count">|<tr id="row-(\d+)">(.*?)</tr>', src, re.S):
    if m.group(1) is not None:
        cat = html.unescape(m.group(1)).strip()
        continue
    body = m.group(3)
    pid = int(m.group(2))
    rate = re.search(r'data-rate="([\d.]+)"', body)
    name = re.search(r'data-pname="([^"]*)"', body)
    code = re.search(r'class="prod-code-sub">\s*Code:\s*([^<]*)<', body)
    if not (rate and name):
        continue
    rows.append((pid, (code.group(1).strip() if code else str(pid)), html.unescape(name.group(1)), float(rate.group(1)), cat))

def q(s):
    return "'" + s.replace("'", "''") + "'"

lines = ['-- Generated by supabase/tools/gen_products_sql.py from booknow.html. Safe to run again (updates prices).',
         'insert into public.products (pid, code, name, rate, category) values']
lines.append(',\n'.join(f'  ({p}, {q(c)}, {q(n)}, {r:.2f}, {q(k)})' for p, c, n, r, k in rows))
lines.append('on conflict (pid) do update set code = excluded.code, name = excluded.name, rate = excluded.rate,\n'
             '  category = excluded.category, active = true;')
out = os.path.join(ROOT, 'supabase', 'migrations', '002_seed_products.sql')
open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print(len(rows), 'products ->', out)
